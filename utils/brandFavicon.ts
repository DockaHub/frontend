export const getBrandBgColor = (org?: Partial<Organization> | null): string => {
    if (!org) return '#000000';
    if (org.iconBg) return org.iconBg;

    const slug = org.slug?.toLowerCase() || '';
    switch (slug) {
        case 'asterysko': return '#0412dd';
        case 'manyspace':
        case 'manyways': return '#000000';
        case 'fauves': return '#2a2ad7';
        case 'tokyon': return '#000000';
        case 'umachave': return '#f97316';
        case 'allyo': return '#0d1e1d';
        case 'niva': return '#1d0c17';
        default: break;
    }

    if (org.logoColor) {
        if (org.logoColor.startsWith('#')) return org.logoColor;
        if (org.logoColor.includes('blue')) return '#2563eb';
        if (org.logoColor.includes('red')) return '#dc2626';
        if (org.logoColor.includes('emerald') || org.logoColor.includes('green')) return '#059669';
        if (org.logoColor.includes('purple')) return '#9333ea';
        if (org.logoColor.includes('orange') || org.logoColor.includes('amber')) return '#ea580c';
        if (org.logoColor.includes('indigo')) return '#4f46e5';
        if (org.logoColor.includes('pink') || org.logoColor.includes('rose')) return '#e11d48';
    }

    return '#18181b';
};

